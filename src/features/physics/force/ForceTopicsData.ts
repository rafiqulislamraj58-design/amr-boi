export const getForceTopicById = (
  id: string
): ForceTopic | undefined => {
  return FORCE_TOPICS.find((topic) => topic.id === id);
};

export const getAllForceTopics = (): ForceTopic[] => {
  return FORCE_TOPICS;
};

export const getForceTopicCount = (): number => {
  return FORCE_TOPICS.length;
};

export const getForceTopicsByDifficulty = (
  difficulty: ForceDifficulty
): ForceTopic[] => {
  return FORCE_TOPICS.filter(
    (topic) => topic.difficulty === difficulty
  );
};

export const getInteractiveForceTopics = (): ForceTopic[] => {
  return FORCE_TOPICS.filter(
    (topic) => topic.lab?.interactive === true
  );
};

export const getForceTopicIndex = (id: string): number => {
  return FORCE_TOPICS.findIndex((topic) => topic.id === id);
};

export const getNextForceTopic = (
  id: string
): ForceTopic | undefined => {
  const index = getForceTopicIndex(id);

  if (index < 0 || index >= FORCE_TOPICS.length - 1) {
    return undefined;
  }

  return FORCE_TOPICS[index + 1];
};

export const getPreviousForceTopic = (
  id: string
): ForceTopic | undefined => {
  const index = getForceTopicIndex(id);

  if (index <= 0) {
    return undefined;
  }

  return FORCE_TOPICS[index - 1];
};

export const searchForceTopics = (
  query: string
): ForceTopic[] => {
  const normalizedQuery = query.trim().toLowerCase();

  if (!normalizedQuery) {
    return FORCE_TOPICS;
  }

  return FORCE_TOPICS.filter((topic) => {
    const searchableText = [
      topic.title,
      topic.titleEn,
      topic.subtitle,
      topic.summary,
      ...topic.explanation,
      ...topic.keyPoints,
      ...topic.tags
    ]
      .join(' ')
      .toLowerCase();

    return searchableText.includes(normalizedQuery);
  });
};
