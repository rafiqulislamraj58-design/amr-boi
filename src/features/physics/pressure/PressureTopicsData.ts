/**
 * Find a pressure topic using its unique ID.
 */
export const getPressureTopicById = (
  id: string
): PressureTopic | undefined => {
  return PRESSURE_TOPICS.find((topic) => topic.id === id);
};

/**
 * Find a pressure topic using its chapter number.
 */
export const getPressureTopicByNumber = (
  number: string
): PressureTopic | undefined => {
  return PRESSURE_TOPICS.find((topic) => topic.number === number);
};

/**
 * Search pressure topics by Bengali or English title.
 */
export const searchPressureTopics = (
  query: string
): PressureTopic[] => {
  const normalizedQuery = query.trim().toLowerCase();

  if (!normalizedQuery) {
    return PRESSURE_TOPICS;
  }

  return PRESSURE_TOPICS.filter((topic) => {
    return (
      topic.title.toLowerCase().includes(normalizedQuery) ||
      topic.titleEn.toLowerCase().includes(normalizedQuery) ||
      topic.summary.toLowerCase().includes(normalizedQuery) ||
      topic.id.toLowerCase().includes(normalizedQuery)
    );
  });
};

/**
 * Get total pressure topic count.
 */
export const getPressureTopicCount = (): number => {
  return PRESSURE_TOPICS.length;
};
